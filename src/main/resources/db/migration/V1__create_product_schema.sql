-- =====================================================================
-- PRODUCTS DB (TDD §9.2) — NO QUANTITY, NO PRICE: those live in
-- Inventory Service (quantity) and Supplier Service offers (price).
-- =====================================================================

CREATE TABLE categories (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   NUMBER(19) REFERENCES categories(id),
    slug        VARCHAR2(120) NOT NULL UNIQUE,
    name        VARCHAR2(160) NOT NULL,
    -- Slug chain from the root, e.g. '/electronics/mobiles/smartphones'.
    path        VARCHAR2(1000) NOT NULL,
    is_active   BOOLEAN DEFAULT TRUE NOT NULL,
    version     NUMBER(19) DEFAULT 0 NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX idx_categories_path ON categories (path);
CREATE INDEX idx_categories_parent ON categories (parent_id);

CREATE TABLE brands (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR2(120) NOT NULL UNIQUE,
    name        VARCHAR2(160) NOT NULL,
    is_active   BOOLEAN DEFAULT TRUE NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE products (
    id              RAW(16) DEFAULT SYS_GUID() PRIMARY KEY,
    sku             VARCHAR2(64) NOT NULL,
    gtin            VARCHAR2(20),
    title           VARCHAR2(500) NOT NULL,
    description     VARCHAR2(32767),
    brand_id        NUMBER(19) REFERENCES brands(id),
    category_id     NUMBER(19) NOT NULL REFERENCES categories(id),
    attributes      JSON DEFAULT '{}' NOT NULL,
    media_root      VARCHAR2(500),
    status          VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL
                    CHECK (status IN ('DRAFT','ACTIVE','HIDDEN','DELISTED')),
    weight_grams    NUMBER(10),
    dim_l_mm        NUMBER(10),
    dim_w_mm        NUMBER(10),
    dim_h_mm        NUMBER(10),
    is_hazardous    BOOLEAN DEFAULT FALSE NOT NULL,
    version         NUMBER(19) DEFAULT 0 NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    deleted_at      TIMESTAMP WITH TIME ZONE
);
-- SKU and GTIN are unique among live products; a soft-deleted product frees them for reuse.
-- Oracle has no partial indexes: a unique function-based index ignores rows where the CASE is NULL.
CREATE UNIQUE INDEX uq_products_sku
    ON products (CASE WHEN deleted_at IS NULL THEN sku END);
CREATE UNIQUE INDEX uq_products_gtin
    ON products (CASE WHEN gtin IS NOT NULL AND deleted_at IS NULL THEN gtin END);
CREATE INDEX idx_products_category ON products (category_id, status);
CREATE INDEX idx_products_brand    ON products (brand_id, status);

CREATE TABLE product_media (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  RAW(16) NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    kind        VARCHAR2(20) NOT NULL CHECK (kind IN ('IMAGE','VIDEO','DOCUMENT')),
    url         VARCHAR2(1000) NOT NULL,
    sort_order  NUMBER(10) DEFAULT 0 NOT NULL,
    alt_text    VARCHAR2(255),
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX idx_product_media_pid ON product_media (product_id, sort_order);

CREATE TABLE category_attributes (
    category_id NUMBER(19) NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
    attr_key    VARCHAR2(60) NOT NULL,
    data_type   VARCHAR2(20) NOT NULL CHECK (data_type IN ('STRING','NUMBER','BOOL','ENUM')),
    is_required BOOLEAN DEFAULT FALSE NOT NULL,
    is_facet    BOOLEAN DEFAULT FALSE NOT NULL,
    enum_values JSON,
    PRIMARY KEY (category_id, attr_key)
);

CREATE TABLE product_outbox (
    id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_id RAW(16) NOT NULL,
    event_type   VARCHAR2(60) NOT NULL,
    payload      JSON NOT NULL,
    status       VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    sent_at      TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_prod_outbox_pending ON product_outbox (status, created_at);
